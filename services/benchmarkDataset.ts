/**
 * Builds the exact 7,000-record dataset matching the Build Battle 2026 specifications:
 * Total: 7,000 rows
 * Distinct texts: 320
 * Operational Issues: 1,800 rows (from 80 seeds)
 * Fraud and Scam: 1,755 rows (from 80 seeds)
 * Product Feedback: 1,738 rows (from 80 seeds)
 * Customer Service: 1,707 rows (from 80 seeds)
 */
export function generateBuildBattleBenchmarkRecords(): FeedbackRecord[] {
  const records: FeedbackRecord[] = [];
  let rowId = 1;

  function addCategoryRows(seeds: string[], targetCount: number, category: FeedbackCategory) {
    const seedCount = seeds.length; // 80 seeds
    for (let i = 0; i < targetCount; i++) {
      const text = seeds[i % seedCount];
      records.push({
        id: `bb-row-${rowId}`,
        text,
        category,
        source: 'import',
        rowNumber: rowId,
      });
      rowId++;
    }
  }

  addCategoryRows(OPERATIONAL_SEEDS, 1800, 'Operational Issues');
  addCategoryRows(FRAUD_SEEDS, 1755, 'Fraud and Scam');
  addCategoryRows(PRODUCT_SEEDS, 1738, 'Product Feedback');
  addCategoryRows(CUSTOMER_SERVICE_SEEDS, 1707, 'Customer Service');

  // Total = 1800 + 1755 + 1738 + 1707 = 7,000 rows
  return records;
}

/**
 * Generates the raw CSV string for BuildBattle_2026_Customer_Feedback_Dataset.csv
 * Suitable for download or parsing testing.
 */
export function generateBuildBattleBenchmarkCsvString(): string {
  const records = generateBuildBattleBenchmarkRecords();
  let csv = 'review,category\n';
  for (const r of records) {
    // Escape quotes properly as standard CSV
    const escapedReview = `"${r.text.replace(/"/g, '""')}"`;
    const escapedCategory = `"${r.category}"`;
    csv += `${escapedReview},${escapedCategory}\n`;
  }
  return csv;
}
